CREATE POLICY "rmac_org_members_read_activities"
  ON public.rmac_activities FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.profiles p
      WHERE p.id = (SELECT auth.uid())
        AND p.invite_status = 'active'
        AND (p.org_slug = rmac_activities.org_slug OR p.role = 'deqode_admin')
    )
  );

CREATE POLICY "rmac_members_submit_activities"
  ON public.rmac_activities FOR INSERT
  TO authenticated
  WITH CHECK (
    created_by = (SELECT auth.uid())
    AND EXISTS (
      SELECT 1
      FROM public.profiles p
      WHERE p.id = (SELECT auth.uid())
        AND p.invite_status = 'active'
        AND p.org_slug = rmac_activities.org_slug
    )
  );

CREATE POLICY "rmac_reviewers_update_activities"
  ON public.rmac_activities FOR UPDATE
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.profiles p
      WHERE p.id = (SELECT auth.uid())
        AND p.invite_status = 'active'
        AND p.role IN ('analyst', 'admin', 'deqode_admin')
        AND (p.org_slug = rmac_activities.org_slug OR p.role = 'deqode_admin')
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public.profiles p
      WHERE p.id = (SELECT auth.uid())
        AND p.invite_status = 'active'
        AND p.role IN ('analyst', 'admin', 'deqode_admin')
        AND (p.org_slug = rmac_activities.org_slug OR p.role = 'deqode_admin')
    )
  );

CREATE POLICY "rmac_org_members_read_evidence"
  ON public.rmac_activity_evidence FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.rmac_activities a
      JOIN public.profiles p ON p.id = (SELECT auth.uid())
      WHERE a.id = rmac_activity_evidence.activity_id
        AND p.invite_status = 'active'
        AND (p.org_slug = a.org_slug OR p.role = 'deqode_admin')
    )
  );

CREATE POLICY "rmac_members_add_evidence"
  ON public.rmac_activity_evidence FOR INSERT
  TO authenticated
  WITH CHECK (
    created_by = (SELECT auth.uid())
    AND EXISTS (
      SELECT 1
      FROM public.rmac_activities a
      JOIN public.profiles p ON p.id = (SELECT auth.uid())
      WHERE a.id = rmac_activity_evidence.activity_id
        AND a.created_by = (SELECT auth.uid())
        AND p.invite_status = 'active'
        AND p.org_slug = a.org_slug
    )
  );

