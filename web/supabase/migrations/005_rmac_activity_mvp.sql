CREATE OR REPLACE FUNCTION public.set_rmac_activity_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS rmac_activity_updated_at ON public.rmac_activities;
CREATE TRIGGER rmac_activity_updated_at
  BEFORE UPDATE ON public.rmac_activities
  FOR EACH ROW EXECUTE FUNCTION public.set_rmac_activity_updated_at();

